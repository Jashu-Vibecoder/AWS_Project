param(
    [Parameter(Mandatory = $true)][string]$BucketName,
    [Parameter(Mandatory = $true)][string]$FlaskApiBaseUrl,
    [Parameter(Mandatory = $true)][string]$FileApiBaseUrl,
    [switch]$AuthRequired,
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'
$Region = 'ap-southeast-2'
$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$ConfigPath = Join-Path $ProjectRoot 'frontend\js\config.js'

if (-not (Get-Command aws -ErrorAction SilentlyContinue)) { throw 'AWS CLI v2 was not found in PATH.' }
if ($BucketName -notmatch '^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$') { throw 'BucketName is not a valid S3 bucket name.' }
foreach ($url in @($FlaskApiBaseUrl, $FileApiBaseUrl)) {
    try { $parsedUrl = [Uri]$url } catch { throw 'Production API URLs must be valid HTTPS origins.' }
    if (-not $parsedUrl.IsAbsoluteUri -or
        $parsedUrl.Scheme -ne 'https' -or
        -not $parsedUrl.Host -or
        $parsedUrl.UserInfo -or
        $parsedUrl.Query -or
        $parsedUrl.Fragment -or
        $parsedUrl.AbsolutePath -ne '/') {
        throw 'Production API URLs must be HTTPS origins without credentials, paths, queries, or fragments.'
    }
}
$account = (& aws sts get-caller-identity --region $Region --query Account --output text).Trim()
if ($LASTEXITCODE -ne 0) { throw 'AWS caller identity check failed.' }
Write-Host "AWS account $account; region $Region; target bucket $BucketName"
Write-Host 'This operation updates local frontend config and uploads files to the existing bucket. It does not delete remote files.'
if (-not $Apply) { Write-Host 'Preflight only. Review the values, then rerun with -Apply to publish.'; return }

$auth = if ($AuthRequired) { 'true' } else { 'false' }
$flaskUrlJson = ConvertTo-Json -InputObject $FlaskApiBaseUrl -Compress
$fileUrlJson = ConvertTo-Json -InputObject $FileApiBaseUrl -Compress
$config = @"
/* Generated by deployment/deploy_frontend.ps1. Contains URLs only, never credentials. */
window.CLOUDBOX_CONFIG = Object.freeze({
  flaskApiBaseUrl: $flaskUrlJson,
  fileApiBaseUrl: $fileUrlJson,
  authRequired: $auth,
});
"@
Set-Content -LiteralPath $ConfigPath -Value $config -Encoding utf8
& aws s3 sync (Join-Path $ProjectRoot 'frontend') "s3://$BucketName" --region $Region --only-show-errors
if ($LASTEXITCODE -ne 0) { throw 'S3 sync failed. No remote files were deleted.' }
Write-Host 'Frontend files uploaded. Verify the CloudFront website and API calls.'
